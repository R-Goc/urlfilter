package filterlist

import (
	"bufio"
	"bytes"
	"io"

	"github.com/AdguardTeam/urlfilter/rules"
)

// RuleScanner implements an interface for reading filtering rules.
type RuleScanner struct {
	// reader reads the source.
	reader *bufio.Reader

	// currentRule is the last read rule.
	currentRule rules.Rule

	// listID is the filter list ID.
	listID rules.ListID

	// currentPos is the current position in the reader.
	currentPos int64

	// currentRuleIndex is the index of the beginning of the current rule.
	currentRuleIndex int64

	// ignoreCosmetic tells whether to ignore cosmetic rules or not.
	ignoreCosmetic bool
}

// NewRuleScanner returns a new RuleScanner to read from the given reader.
func NewRuleScanner(r io.Reader, id rules.ListID, ignoreCosmetic bool) (s *RuleScanner) {
	return &RuleScanner{
		listID:         id,
		ignoreCosmetic: ignoreCosmetic,
		reader:         bufio.NewReaderSize(r, int(readerBufferSize)),
	}
}

// Scan advances the RuleScanner to the next rule, which will then be available
// through the Rule method. It returns false when the scan stops, either by
// reaching the end of the input or an error.
func (s *RuleScanner) Scan() (ok bool) {
	for {
		line, idx, err := s.readNextLine()
		if err != nil {
			return false
		}

		rule, err := rules.NewRule(line, s.listID)
		// TODO(a.garipov):  Ignore cosmetic earlier in the process when they're
		// still in []byte.
		if rule != nil && err == nil && !s.isIgnored(rule) {
			s.currentRule = rule
			s.currentRuleIndex = idx

			return true
		}
	}
}

// Rule returns the most recent rule generated by a call to Scan, and the index
// of this rule's text.
func (s *RuleScanner) Rule() (r rules.Rule, idx int64) {
	return s.currentRule, s.currentRuleIndex
}

// CountSimpleDomains scans s to EOF and returns the number of pure simple
// domain rules ("||domain^" / "@@||domain^") without allocating rules.
func (s *RuleScanner) CountSimpleDomains() (n int) {
	for {
		chunk, _, err := s.readNextLineBytes()
		if err != nil {
			return n
		}

		trimmed := bytes.TrimSpace(chunk)
		if len(trimmed) == 0 || trimmed[0] == '!' {
			continue
		}

		if trimmed[0] == '#' {
			// Skip non-cosmetic '#' comment lines without allocating a string.
			if len(trimmed) == 1 {
				continue
			}
			switch trimmed[1] {
			case '#', '@', '?', '$', '%':
			default:
				continue
			}
		}

		if _, ok := parseSimpleDomainRuleBytes(trimmed); ok {
			n++
		}
	}
}

// ScanFast advances s to the next rule, returning either a zero-allocation
// simple pure-domain slice (for "||domain^" or "@@||domain^" lines) or a parsed
// [rules.Rule].  The returned simpleDomain slice is only valid until the next
// scan call.
func (s *RuleScanner) ScanFast() (
	simpleDomain []byte,
	rule rules.Rule,
	listID rules.ListID,
	idx int64,
	ok bool,
) {
	for {
		chunk, lineIdx, err := s.readNextLineBytes()
		if err != nil {
			return nil, nil, 0, 0, false
		}

		trimmed := bytes.TrimSpace(chunk)
		if len(trimmed) == 0 || trimmed[0] == '!' {
			continue
		}

		if trimmed[0] == '#' {
			// Skip non-cosmetic '#' comment lines without allocating a string.
			if len(trimmed) == 1 {
				continue
			}
			switch trimmed[1] {
			case '#', '@', '?', '$', '%':
			default:
				continue
			}
		}

		if dom, isSimple := parseSimpleDomainRuleBytes(trimmed); isSimple {
			return dom, nil, s.listID, lineIdx, true
		}

		r, parseErr := rules.NewRule(string(trimmed), s.listID)
		if r != nil && parseErr == nil && !s.isIgnored(r) {
			return nil, r, s.listID, lineIdx, true
		}
	}
}

// readNextLineBytes reads the next line using ReadSlice to avoid allocating a
// byte slice copy on the common path.
func (s *RuleScanner) readNextLineBytes() (chunk []byte, idx int64, err error) {
	lineIndex := s.currentPos

	chunk, err = s.reader.ReadSlice('\n')
	if err != bufio.ErrBufferFull {
		if err != nil && err != io.EOF {
			return nil, lineIndex, err
		}

		if len(chunk) > 0 {
			s.currentPos += int64(len(chunk))

			return chunk, lineIndex, nil
		}

		if err != nil {
			return nil, lineIndex, io.EOF
		}

		return nil, lineIndex, nil
	}

	full := make([]byte, len(chunk), len(chunk)*2)
	copy(full, chunk)
	for err == bufio.ErrBufferFull {
		chunk, err = s.reader.ReadSlice('\n')
		full = append(full, chunk...)
	}

	if err != nil && err != io.EOF {
		return nil, lineIndex, err
	}

	s.currentPos += int64(len(full))

	return full, lineIndex, nil
}

// parseSimpleDomainRuleBytes checks whether line is a pure domain rule of the
// form "||<domain>^" or "@@||<domain>^" containing only ASCII domain characters
// and at least one dot.
func parseSimpleDomainRuleBytes(line []byte) (domain []byte, ok bool) {
	// Optional allowlist prefix: "@@".
	b, _ := bytes.CutPrefix(line, []byte("@@"))

	// Required domain-anchor prefix: "||".
	b, ok = bytes.CutPrefix(b, []byte("||"))
	if !ok {
		return nil, false
	}

	// Required separator suffix: "^".
	b, ok = bytes.CutSuffix(b, []byte("^"))
	if !ok || len(b) == 0 {
		return nil, false
	}

	hasDot := false
	for _, c := range b {
		if c == '.' {
			hasDot = true

			continue
		}

		isValid := (c >= 'a' && c <= 'z') ||
			(c >= 'A' && c <= 'Z') ||
			(c >= '0' && c <= '9') ||
			c == '-' || c == '_'
		if !isValid {
			return nil, false
		}
	}

	if !hasDot {
		return nil, false
	}

	return b, true
}

// readNextLine reads the next line and returns it and the index of the
// beginning of the string.
func (s *RuleScanner) readNextLine() (line string, idx int64, err error) {
	chunk, idx, err := s.readNextLineBytes()
	if err != nil {
		return "", idx, err
	}

	return string(chunk), idx, nil
}

// isIgnored checks if the rule should be ignored by this scanner.
func (s *RuleScanner) isIgnored(f rules.Rule) (ignored bool) {
	if !s.ignoreCosmetic {
		return false
	}

	if _, ok := f.(*rules.CosmeticRule); ok {
		return true
	}

	return false
}
